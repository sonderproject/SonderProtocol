#!/usr/bin/env python3
"""Build live.html — the Live Conditions map (National Weather Service alerts by state).

Run:  python3 tools/build_live.py   (re-run after changing the homepage header)
Data comes from /api/alerts at runtime; this page is static markup + assets/js/live.js.
"""
from pathlib import Path

# Tile-grid layout of the US: state -> (column, row) on a 12 x 8 grid.
TILES = {
    "AK": (0, 0), "ME": (11, 0),
    "VT": (10, 1), "NH": (11, 1),
    "WA": (1, 2), "ID": (2, 2), "MT": (3, 2), "ND": (4, 2), "MN": (5, 2), "IL": (6, 2), "WI": (7, 2), "MI": (8, 2), "NY": (9, 2), "RI": (10, 2), "MA": (11, 2),
    "OR": (1, 3), "NV": (2, 3), "WY": (3, 3), "SD": (4, 3), "IA": (5, 3), "IN": (6, 3), "OH": (7, 3), "PA": (8, 3), "NJ": (9, 3), "CT": (10, 3),
    "CA": (1, 4), "UT": (2, 4), "CO": (3, 4), "NE": (4, 4), "MO": (5, 4), "KY": (6, 4), "WV": (7, 4), "VA": (8, 4), "MD": (9, 4), "DE": (10, 4),
    "AZ": (2, 5), "NM": (3, 5), "KS": (4, 5), "AR": (5, 5), "TN": (6, 5), "NC": (7, 5), "SC": (8, 5), "DC": (9, 5),
    "OK": (4, 6), "LA": (5, 6), "MS": (6, 6), "AL": (7, 6), "GA": (8, 6),
    "HI": (0, 7), "TX": (4, 7), "FL": (9, 7),
}


def build():
    root = Path(__file__).resolve().parent.parent
    index = (root / "index.html").read_text()
    head_links = index[index.index('<link rel="icon"'):index.index('<link rel="preload"')]
    header = index[index.index('  <header class="site-header"'):index.index('  </header>') + len('  </header>')]
    for anchor in ("#inside", "#kit", "#faq", "#buy"):
        header = header.replace(f'href="{anchor}"', f'href="/{anchor}"')
    header = header.replace('href="#top"', 'href="/"')

    tiles = "\n".join(
        f'          <button class="tile-state" data-state="{s}" style="--c:{c + 1};--r:{r + 1}" aria-label="{s}: loading">{s}</button>'
        for s, (c, r) in TILES.items())

    html = f'''<!doctype html>
<!-- GENERATED by tools/build_live.py — edit that script, not this file. -->
<html lang="en" data-bonus="on">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>Live Weather Alert Map — Sonder Protocol</title>
  <meta name="description" content="Live map of active National Weather Service alerts across the United States: winter storms, hurricanes, floods, heat, and fire weather, updated every few minutes." />
  <meta name="theme-color" content="#06080a" />
  {head_links.strip()}
  <link rel="stylesheet" href="assets/css/styles.css" />
</head>
<body class="page-live">
  <a class="skip-link" href="#main">Skip to content</a>

{header}

  <main id="main">
    <section class="live-hero">
      <div class="aurora" aria-hidden="true"></div>
      <div class="grain" aria-hidden="true"></div>
      <div class="container live-hero__inner">
        <p class="pill reveal"><span class="pill__dot"></span>Live Conditions</p>
        <h1 class="block__title reveal">What's happening<br /><span class="muted">across the country, right now.</span></h1>
        <p class="live-hero__sub reveal">Active National Weather Service alerts by state: winter storms, hurricanes, floods, extreme heat, and fire weather. Tap a state to see what's in effect.</p>
      </div>
    </section>

    <section class="live">
      <div class="container">
        <div class="live__bar">
          <p class="live__status" data-live-status><span class="dot dot--orange pulse"></span>Loading live alerts…</p>
          <ul class="live__legend" aria-label="Alert level legend">
            <li><i class="lv lv--Extreme"></i>Extreme</li>
            <li><i class="lv lv--Severe"></i>Severe</li>
            <li><i class="lv lv--Moderate"></i>Moderate</li>
            <li><i class="lv lv--Minor"></i>Minor</li>
            <li><i class="lv lv--Clear"></i>No alerts</li>
          </ul>
        </div>

        <div class="live__layout">
          <div class="panel live__map" role="group" aria-label="United States alert map">
            <div class="tile-grid">
{tiles}
            </div>
          </div>

          <aside class="panel live__detail" data-live-detail aria-live="polite">
            <p class="label"><span class="label__n">—</span><i class="label__rule"></i><span>Select a state</span></p>
            <p class="live__hint">Tap any state on the map to see its active alerts.</p>
          </aside>
        </div>

        <p class="live__note">Source: National Weather Service (api.weather.gov), refreshed every 5 minutes. For emergencies, follow your local officials and call 911. Power outage data is not shown.</p>
      </div>
    </section>

    <section class="cta" id="buy">
      <div class="aurora" aria-hidden="true"></div>
      <div class="container cta__inner reveal">
        <p class="pill"><span class="pill__dot"></span>Protocol 001 · The Blackout Kit</p>
        <h2 class="cta__title">Storms knock out power.<br /><span class="shimmer">Be ready before they do.</span></h2>
        <p class="cta__sub">The 30-Day Blackout Playbook and free Buy List: exactly what your household needs and what to do, hour by hour.</p>
        <div class="cta__form"><a href="/#buy" class="btn btn--primary btn--lg shine">Get the Blackout Kit <span class="btn__arrow">→</span></a></div>
      </div>
    </section>
  </main>

  <footer class="footer">
    <div class="container footer__base">
      <span>© <span data-year>2026</span> Sonder Protocol. Alert data: National Weather Service.</span>
      <span class="mono"><a href="/">Home</a> · <a href="/gear">Gear</a> · <a href="/live">Live Map</a></span>
    </div>
  </footer>

  <script src="https://cdn.jsdelivr.net/npm/lenis@1.1.13/dist/lenis.min.js" defer></script>
  <script src="assets/js/main.js" defer></script>
  <script src="assets/js/live.js" defer></script>
</body>
</html>
'''
    (root / "live.html").write_text(html)
    print(f"live.html written: {len(TILES)} states")


if __name__ == "__main__":
    build()
